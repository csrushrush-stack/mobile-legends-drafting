# -*- coding: utf-8 -*-
"""Generate lane_roles.py from scraped mldb lineups.

The app used to guess every hero's lane from a hand-written table. This turns
the measured player-role data into a real lane map: which lane each hero was
actually fielded in, how often, and how split it is.

A hero qualifies for a measured primary once it has MIN_N games of evidence;
below that the hand-coded fallback in build_draft_app.py stays in charge.
A lane is listed as playable at MIN_SHARE of the hero's games.

Usage: python build_lane_roles.py [roles.json]
"""
import io, json, os, sys
from collections import defaultdict

SRC = sys.argv[1] if len(sys.argv) > 1 else "mldb_ph18_roles.json"
OUT = "lane_roles.py"
MIN_N = 6        # games before we trust a measured primary
MIN_SHARE = 0.15  # share of games before a lane counts as playable
MIN_LANE_N = 2    # and at least this many games in that lane
ROLE = {"EXP LANER": "EXP", "GOLD LANER": "Gold", "MID LANER": "Mid",
        "JUNGLER": "Jungle", "ROAMER": "Roam"}
LANES = ["EXP", "Jungle", "Mid", "Gold", "Roam"]


def squash(s):
    return "".join(c for c in (s or "").lower() if c.isalnum())


def collect(path):
    counts = defaultdict(lambda: defaultdict(int))
    for m in json.load(io.open(path, encoding="utf-8")):
        roles, roles_name = m.get("roles") or {}, m.get("rolesName") or {}
        for k in m.get("picks") or []:
            slug = (k.get("playerSlug") or "").lower()
            role = roles.get(slug) or roles_name.get(squash(k.get("player")))
            lane = ROLE.get((role or "").strip().upper())
            if lane:
                counts[k["hero"]][lane] += 1
    return counts


def main():
    counts = collect(SRC)
    out = {}
    for hero, lanes in counts.items():
        n = sum(lanes.values())
        if n < 3:
            continue
        primary = max(lanes.items(), key=lambda kv: (kv[1], -LANES.index(kv[0])))[0]
        playable = [l for l in LANES
                    if lanes.get(l, 0) >= MIN_LANE_N and lanes[l] / n >= MIN_SHARE]
        out[hero] = dict(n=n, primary=primary, lanes=playable,
                         share={l: round(lanes[l] / n * 100, 1) for l in LANES if lanes.get(l)})

    lines = ['# -*- coding: utf-8 -*-',
             '"""MEASURED lane usage, generated by build_lane_roles.py.',
             '',
             'Source: %s - %d matches of real MPL PH S18 lineups.' % (SRC, len(json.load(io.open(SRC, encoding="utf-8")))),
             'Each entry records the lane a hero was actually fielded in, taken from the',
             "player's roster role on mldb.gg, not from a hand-written table.",
             '',
             'n        games observed',
             'primary  lane with the most games',
             'lanes    lanes played in >= %d%% of games (and >= %d games)' % (MIN_SHARE * 100, MIN_LANE_N),
             'share    percentage split across lanes',
             '"""',
             '',
             'MIN_N = %d' % MIN_N,
             '',
             'MEASURED = {']
    for hero in sorted(out, key=lambda h: -out[h]["n"]):
        d = out[hero]
        lines.append('    %r: dict(n=%d, primary=%r, lanes=%r, share=%r),'
                     % (hero, d["n"], d["primary"], d["lanes"], d["share"]))
    lines.append('}')
    lines.append('')
    io.open(OUT, "w", encoding="utf-8").write("\n".join(lines))

    print("wrote %s: %d heroes measured" % (OUT, len(out)))
    moved = [(h, d) for h, d in out.items() if d["n"] >= MIN_N]
    print("trusted primaries (n>=%d): %d" % (MIN_N, len(moved)))


if __name__ == "__main__":
    main()
